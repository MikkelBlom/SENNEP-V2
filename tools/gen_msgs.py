#!/usr/bin/env python3
"""Generate protocol code from protocol/messages.json.

Outputs (never edit these by hand):
  firmware/libraries/SennepProto/src/sennep_msgs.h   C99 structs + pack/unpack
  tools/sennep_msgs.py                               Python tables
  protocol/MESSAGES.md                               human-readable table

Usage: python3 tools/gen_msgs.py [--check]   (--check: fail if outputs are stale)
"""
import json
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "protocol" / "messages.json"
OUT_H = ROOT / "firmware" / "libraries" / "SennepProto" / "src" / "sennep_msgs.h"
OUT_PY = ROOT / "tools" / "sennep_msgs.py"
OUT_MD = ROOT / "protocol" / "MESSAGES.md"

SCALARS = {  # name: (C type, struct fmt, size)
    "u8": ("uint8_t", "B", 1), "i8": ("int8_t", "b", 1),
    "u16": ("uint16_t", "H", 2), "i16": ("int16_t", "h", 2),
    "u32": ("uint32_t", "I", 4), "i32": ("int32_t", "i", 4),
    "f32": ("float", "f", 4),
}


def parse_type(t):
    m = re.fullmatch(r"(u8|i8|u16|i16|u32|i32|f32)(?:\[(\d*)\])?", t)
    if not m:
        raise SystemExit(f"bad type {t!r}")
    base, count = m.group(1), m.group(2)
    if count is None:
        return base, 1, False
    if count == "":
        if base != "u8":
            raise SystemExit("variable tail must be u8[]")
        return base, 0, True
    return base, int(count), False


def load():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    # Hash the parsed content, not the file bytes, so CRLF/LF checkouts (Windows vs Pi) agree.
    canon = json.dumps(spec, sort_keys=True, separators=(",", ":")).encode()
    spec_hash = zlib.crc32(canon) & 0xFFFFFFFF
    ids = set()
    for msg in spec["messages"]:
        mid = int(msg["id"], 16)
        if mid in ids:
            raise SystemExit(f"duplicate id {msg['id']}")
        ids.add(mid)
        msg["_id"] = mid
        size = 0
        fields = []
        for i, (fname, ftype) in enumerate(msg["fields"]):
            base, count, tail = parse_type(ftype)
            if tail and i != len(msg["fields"]) - 1:
                raise SystemExit(f"{msg['name']}: tail must be last")
            fields.append((fname, base, count, tail))
            if not tail:
                size += SCALARS[base][2] * count
        msg["_fields"] = fields
        msg["_size"] = size
        msg["_tail"] = bool(fields and fields[-1][3])
        if size > spec["max_payload"]:
            raise SystemExit(f"{msg['name']} is {size} B > max_payload")
    return spec, spec_hash


def lower(name):
    return name.lower()


def gen_c(spec, spec_hash):
    mp = spec["max_payload"]
    L = []
    w = L.append
    w("/* GENERATED by tools/gen_msgs.py from protocol/messages.json - DO NOT EDIT. */")
    w("#ifndef SENNEP_MSGS_H")
    w("#define SENNEP_MSGS_H")
    w('#include "sennep_proto.h"')
    w("#ifdef __cplusplus")
    w('extern "C" {')
    w("#endif")
    w("")
    w(f"#define SP_PROTOCOL_VERSION {spec['protocol_version']}u")
    w(f"#define SP_SPEC_HASH 0x{spec_hash:08X}ul")
    w(f"#if SP_MAX_PAYLOAD != {mp}")
    w("#error SP_MAX_PAYLOAD in sennep_proto.h does not match messages.json")
    w("#endif")
    w("")
    for ename, values in spec["enums"].items():
        for k, v in values.items():
            w(f"#define SP_{ename}_{k} {v}u")
        w("")
    for msg in spec["messages"]:
        n, ln = msg["name"], lower(msg["name"])
        w(f"/* 0x{msg['_id']:02X} {n} ({msg['dir']}): {msg['doc']} */")
        w(f"#define SP_MSG_{n} 0x{msg['_id']:02X}u")
        w(f"#define SP_SIZE_{n} {msg['_size']}u" + ("  /* + variable tail */" if msg["_tail"] else ""))
        w("typedef struct {")
        if not msg["_fields"]:
            w("    uint8_t _unused;")
        for fname, base, count, tail in msg["_fields"]:
            ct = SCALARS[base][0]
            if tail:
                w(f"    uint8_t {fname}[SP_MAX_PAYLOAD - {msg['_size']}];")
                w(f"    uint8_t {fname}_len;")
            elif count > 1:
                w(f"    {ct} {fname}[{count}];")
            else:
                w(f"    {ct} {fname};")
        w(f"}} sp_{ln}_t;")
        # pack
        w(f"static inline uint8_t sp_pack_{ln}(const sp_{ln}_t *m, uint8_t *p) {{")
        w("    uint8_t o = 0;")
        if not msg["_fields"]:
            w("    (void)m; (void)p;")
        for fname, base, count, tail in msg["_fields"]:
            if tail:
                w(f"    sp_memcpy(p + o, m->{fname}, m->{fname}_len); o = (uint8_t)(o + m->{fname}_len);")
            elif count > 1:
                w(f"    for (uint8_t i = 0; i < {count}; i++) {{ sp_put_{base}(p + o, m->{fname}[i]); o = (uint8_t)(o + {SCALARS[base][2]}); }}")
            else:
                w(f"    sp_put_{base}(p + o, m->{fname}); o = (uint8_t)(o + {SCALARS[base][2]});")
        w("    return o;")
        w("}")
        # unpack
        w(f"static inline bool sp_unpack_{ln}(const uint8_t *p, uint8_t len, sp_{ln}_t *m) {{")
        if msg["_tail"]:
            w(f"    if (len < SP_SIZE_{n}) return false;")
        else:
            w(f"    if (len != SP_SIZE_{n}) return false;")
        w("    uint8_t o = 0;")
        if not msg["_fields"]:
            w("    (void)p; (void)m; (void)o;")
        for fname, base, count, tail in msg["_fields"]:
            if tail:
                w(f"    m->{fname}_len = (uint8_t)(len - o); sp_memcpy(m->{fname}, p + o, m->{fname}_len);")
            elif count > 1:
                w(f"    for (uint8_t i = 0; i < {count}; i++) {{ m->{fname}[i] = sp_get_{base}(p + o); o = (uint8_t)(o + {SCALARS[base][2]}); }}")
            else:
                w(f"    m->{fname} = sp_get_{base}(p + o); o = (uint8_t)(o + {SCALARS[base][2]});")
        w("    return true;")
        w("}")
        w("")
    w("#ifdef __cplusplus")
    w("}")
    w("#endif")
    w("#endif")
    return "\n".join(L) + "\n"


def gen_py(spec, spec_hash):
    L = ['"""GENERATED by tools/gen_msgs.py from protocol/messages.json - DO NOT EDIT."""', ""]
    w = L.append
    w(f"PROTOCOL_VERSION = {spec['protocol_version']}")
    w(f"SPEC_HASH = 0x{spec_hash:08X}")
    w(f"MAX_PAYLOAD = {spec['max_payload']}")
    w("")
    for ename, values in spec["enums"].items():
        w(f"class {ename}:")
        for k, v in values.items():
            w(f"    {k} = {v}")
        w("")
    w("# id: (name, direction, struct format without '<', [(field, count)], has_tail)")
    w("MESSAGES = {")
    for msg in spec["messages"]:
        fmt = "".join((str(c) if c > 1 else "") + SCALARS[b][1] for _, b, c, t in msg["_fields"] if not t)
        fl = [(f, -1 if t else c) for f, b, c, t in msg["_fields"]]
        w(f"    0x{msg['_id']:02X}: ({msg['name']!r}, {msg['dir']!r}, {fmt!r}, {fl!r}, {msg['_tail']}),")
    w("}")
    w("BY_NAME = {v[0]: k for k, v in MESSAGES.items()}")
    return "\n".join(L) + "\n"


def gen_md(spec, spec_hash):
    L = ["# Beskeder — SENNEP Pi ↔ Mega", "",
         f"> Genereret fra `messages.json` af `tools/gen_msgs.py`. Protokolversion {spec['protocol_version']}, "
         f"spec-hash `0x{spec_hash:08X}`, maks payload {spec['max_payload']} bytes. Little-endian.", "",
         "Frame på ledningen: `COBS( type u8 | seq u8 | payload | crc16 u16 ) 0x00`, CRC-16/CCITT-FALSE over type+seq+payload.", "",
         "| Id | Navn | Retning | Bytes | Felter | Beskrivelse |", "|---|---|---|---:|---|---|"]
    for msg in spec["messages"]:
        fields = ", ".join(f"{f} `{t}`" for f, t in msg["fields"]) or "—"
        size = f"{msg['_size']}+" if msg["_tail"] else str(msg["_size"])
        arrow = "Pi → Mega" if msg["dir"] == "pi2mega" else "Mega → Pi"
        L.append(f"| 0x{msg['_id']:02X} | `{msg['name']}` | {arrow} | {size} | {fields} | {msg['doc']} |")
    L += ["", "## Konstanter", ""]
    for ename, values in spec["enums"].items():
        L.append(f"- **{ename}:** " + ", ".join(f"{k} = {v}" for k, v in values.items()))
    return "\n".join(L) + "\n"


def main():
    spec, spec_hash = load()
    outputs = {OUT_H: gen_c(spec, spec_hash), OUT_PY: gen_py(spec, spec_hash), OUT_MD: gen_md(spec, spec_hash)}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
        if stale:
            raise SystemExit("stale generated files: " + ", ".join(stale) + " -> run tools/gen_msgs.py")
        print("generated files up to date")
        return
    for p, s in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(s)
        print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
